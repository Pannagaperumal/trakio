#!/usr/bin/env python3
"""Rasterise Montserrat into LVGL 8 bitmap fonts (4 bpp, no kerning).

    python3 tools/gen_fonts.py <dir-with-Montserrat-Bold.ttf-and-SemiBold.ttf>

Writes src/fonts/font_*.c. The TTFs come from
https://github.com/JulietaUla/Montserrat (SIL Open Font License 1.1).
"""
import os
import sys

from PIL import ImageFont

ASCII = list(range(0x20, 0x7F)) + [0xB0, 0xB7, 0x2026]   # + ° · …
FONTS = [
    # name,          file,                     size, codepoints
    ("font_num104", "Montserrat-Bold.ttf",     104,  [ord(c) for c in " -.0123456789:"]),
    ("font_num56",  "Montserrat-Bold.ttf",      56,  [ord(c) for c in " .0123456789km"]),
    ("font_bold44", "Montserrat-Bold.ttf",      44,  ASCII),
    ("font_bold34", "Montserrat-Bold.ttf",      34,  ASCII),
    ("font_semi23", "Montserrat-SemiBold.ttf",  23,  ASCII),
    ("font_semi18", "Montserrat-SemiBold.ttf",  18,  ASCII),
]


def glyph(font, cp):
    ch = chr(cp)
    adv = font.getlength(ch)
    mask, (ox, oy) = font.getmask2(ch, mode="L", anchor="ls")
    w, h = mask.size
    px = [mask.getpixel((x, y)) for y in range(h) for x in range(w)]
    if w == 0 or h == 0 or not any(px):
        return adv, 0, 0, 0, 0, b""
    # trim empty rows/cols so boxes stay tight
    rows = [px[r * w:(r + 1) * w] for r in range(h)]
    top = next(i for i, r in enumerate(rows) if any(r))
    bot = h - next(i for i, r in enumerate(reversed(rows)) if any(r))
    cols = [any(rows[r][c] for r in range(top, bot)) for c in range(w)]
    left = cols.index(True)
    right = w - cols[::-1].index(True)
    rows = [r[left:right] for r in rows[top:bot]]
    bw, bh = right - left, bot - top
    nib = [(v * 15 + 127) // 255 for r in rows for v in r]
    if len(nib) % 2:
        nib.append(0)
    data = bytes((nib[i] << 4) | nib[i + 1] for i in range(0, len(nib), 2))
    ofs_x = ox + left
    ofs_y = -(oy + top + bh)          # LVGL: baseline → bottom of box, y up
    return adv, bw, bh, ofs_x, ofs_y, data


def emit(name, path, size, cps):
    font = ImageFont.truetype(path, size)
    ascent, descent = font.getmetrics()
    cps = sorted(set(cps))
    bitmap = bytearray()
    dsc = ["    {.bitmap_index = 0, .adv_w = 0, .box_w = 0, .box_h = 0, .ofs_x = 0, .ofs_y = 0}"]
    for cp in cps:
        adv, bw, bh, ofs_x, ofs_y, data = glyph(font, cp)
        dsc.append(f"    {{.bitmap_index = {len(bitmap)}, .adv_w = {round(adv * 16)}, .box_w = {bw}, "
                   f".box_h = {bh}, .ofs_x = {ofs_x}, .ofs_y = {ofs_y}}} /* U+{cp:04X} */")
        bitmap += data
    start = cps[0]
    offsets = ", ".join(str(cp - start) for cp in cps)
    hexes = ",\n".join("    " + ", ".join(f"0x{b:02x}" for b in bitmap[i:i + 20]) for i in range(0, len(bitmap), 20))
    return f"""// Generated by tools/gen_fonts.py from {os.path.basename(path)} @ {size}px, 4 bpp.
// Montserrat © The Montserrat Project Authors, SIL Open Font License 1.1.
#include "lvgl.h"

static LV_ATTRIBUTE_LARGE_CONST const uint8_t glyph_bitmap[] = {{
{hexes}
}};

static const lv_font_fmt_txt_glyph_dsc_t glyph_dsc[] = {{
{(","+chr(10)).join(dsc)}
}};

static const uint16_t unicode_list[] = {{ {offsets} }};

static const lv_font_fmt_txt_cmap_t cmaps[] = {{
    {{ .range_start = {start}, .range_length = {cps[-1] - start + 1}, .glyph_id_start = 1,
      .unicode_list = unicode_list, .glyph_id_ofs_list = NULL, .list_length = {len(cps)},
      .type = LV_FONT_FMT_TXT_CMAP_SPARSE_TINY }}
}};

static lv_font_fmt_txt_glyph_cache_t cache;

static const lv_font_fmt_txt_dsc_t font_dsc = {{
    .glyph_bitmap = glyph_bitmap, .glyph_dsc = glyph_dsc, .cmaps = cmaps,
    .kern_dsc = NULL, .kern_scale = 0, .cmap_num = 1, .bpp = 4, .kern_classes = 0,
    .bitmap_format = 0, .cache = &cache,
}};

const lv_font_t {name} = {{
    .get_glyph_dsc = lv_font_get_glyph_dsc_fmt_txt,
    .get_glyph_bitmap = lv_font_get_bitmap_fmt_txt,
    .line_height = {ascent + descent},
    .base_line = {descent},
    .subpx = LV_FONT_SUBPX_NONE,
    .underline_position = -2,
    .underline_thickness = 1,
    .dsc = &font_dsc,
}};
"""


def main():
    src = sys.argv[1] if len(sys.argv) > 1 else "."
    out = os.path.join(os.path.dirname(__file__), "..", "src", "fonts")
    os.makedirs(out, exist_ok=True)
    for name, file, size, cps in FONTS:
        code = emit(name, os.path.join(src, file), size, cps)
        with open(os.path.join(out, name + ".c"), "w") as f:
            f.write(code)
        print(f"{name}: {len(code) // 1024} KB source")


if __name__ == "__main__":
    main()
